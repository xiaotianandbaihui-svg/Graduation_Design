/* SYSCLK单位MHz；仅在调度器启动前调用一次。 */
void delay_init(u8 SYSCLK);
/* 阻塞忙等；供启动前/任务中使用，不在ISR中调用。ms参数最大65535。
 * 调度器运行后SysTick周期为1ms；轮询会累计回绕，调用期间不要停掉/重配SysTick。
 * 中断可响应，故实际延时可能更长；不能用它保证不受中断影响的精确波形。 */
void delay_ms(u16 nms);
void delay_us(u32 nus);

